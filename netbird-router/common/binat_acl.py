#!/usr/bin/env python3
"""Guarded NetBird 0.80 BINAT ACL compatibility.

NetBird's FORWARD ACL matches the virtual destination, after PREROUTING DNAT
has translated it. Replace *only* the native authorization rule; never create
an independent permit. The NetBird dynamic source set and ACL lifecycle remain
authoritative. Unknown NetBird versions/layouts fail closed.
"""
import ipaddress
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile

MARKER = 'openmain-binat-ct-original-v1'
SOURCE_RE = re.compile(r'@nb-[0-9a-f]{8}$')
NETBIRD_OVERLAY = ipaddress.IPv4Network('100.64.0.0/10')
MAX_MANAGED_ACLS = 8
IFACE_RE = re.compile(r'[a-zA-Z0-9_.:-]{1,15}$')
CONFIG = '/etc/nftables.d/openmain-binat-acl.json'


class Refused(Exception):
    pass


def configuration(path=CONFIG):
    item = Path(path)
    if item.is_symlink() or not item.is_file():
        raise Refused('Missing or symbolic-link BINAT configuration')
    meta = item.stat()
    if meta.st_uid != 0 or stat.S_IMODE(meta.st_mode) & 0o022:
        raise Refused('BINAT configuration has unsafe ownership or write access')
    cfg = json.loads(item.read_text())
    if not isinstance(cfg, dict) or set(cfg) != {'overlay', 'lan', 'virtual', 'real'}:
        raise Refused('Invalid BINAT configuration keys')
    if not all(isinstance(cfg[key], str) and IFACE_RE.fullmatch(cfg[key])
               for key in ('overlay', 'lan')):
        raise Refused('Invalid interface')
    if cfg['overlay'] == cfg['lan']:
        raise Refused('BINAT interfaces overlap')
    virtual, real = (ipaddress.IPv4Network(cfg[key], strict=True)
                     for key in ('virtual', 'real'))
    if virtual.prefixlen != real.prefixlen or virtual.overlaps(real):
        raise Refused('Incompatible BINAT networks')
    cfg['virtual'], cfg['real'] = str(virtual), str(real)
    return cfg


def _match(expr, field, value):
    obj = expr.get('match') if isinstance(expr, dict) else None
    return (isinstance(obj, dict) and obj.get('op') == '==' and
            obj.get('left') == {'payload': {'protocol': 'ip', 'field': field}} and
            obj.get('right') == value)


def _prefix(network):
    net = ipaddress.IPv4Network(network)
    return {'prefix': {'addr': str(net.network_address), 'len': net.prefixlen}}


def authorized_source(value):
    """Only NetBird's own dynamic set or a single overlay peer is admissible."""
    if not isinstance(value, str):
        return False
    if SOURCE_RE.fullmatch(value):
        return True
    try:
        return ipaddress.IPv4Address(value) in NETBIRD_OVERLAY
    except ipaddress.AddressValueError:
        return False


def native(rule, cfg):
    expr = rule.get('expr')
    if not isinstance(expr, list) or len(expr) != 4 or any(
            not isinstance(x, dict) for x in expr):
        return None
    match = expr[0].get('match')
    if not isinstance(match, dict) or match.get('op') != '==' or (
            match.get('left') != {'payload': {'protocol': 'ip', 'field': 'saddr'}}):
        return None
    source = match.get('right')
    if not authorized_source(source):
        return None
    if (not _match(expr[1], 'daddr', _prefix(cfg['virtual'])) or
            set(expr[2]) != {'counter'} or expr[3] != {'accept': None}):
        return None
    return source


def managed(rule, cfg):
    # Accept only the exact nftables shape generated by our guarded replacement.
    expr = rule.get('expr')
    if rule.get('comment') != MARKER or not isinstance(expr, list) or len(expr) != 8:
        return False
    def field(index, left, right, op='=='):
        match = expr[index].get('match') if isinstance(expr[index], dict) else None
        return (isinstance(match, dict) and match.get('left') == left
                and match.get('right') == right and match.get('op') == op)
    source = expr[2].get('match', {}).get('right') if isinstance(expr[2], dict) else None
    return (field(0, {'meta': {'key': 'iifname'}}, cfg['overlay'])
            and field(1, {'meta': {'key': 'oifname'}}, cfg['lan'])
            and authorized_source(source)
            and field(2, {'payload': {'protocol': 'ip', 'field': 'saddr'}}, source)
            and field(3, {'ct': {'key': 'status'}}, 'dnat', 'in')
            and field(4, {'ct': {'dir': 'original', 'key': 'daddr'}}, _prefix(cfg['virtual']))
            and field(5, {'payload': {'protocol': 'ip', 'field': 'daddr'}}, _prefix(cfg['real']))
            and isinstance(expr[6], dict) and set(expr[6]) == {'counter'}
            and expr[7] == {'accept': None})


def transaction(rules, cfg):
    if not isinstance(rules, dict) or not isinstance(rules.get('nftables'), list):
        raise Refused('Invalid nftables response')
    candidates, existing = [], []
    for entry in rules['nftables']:
        rule = entry.get('rule') if isinstance(entry, dict) else None
        if (not isinstance(rule, dict) or rule.get('family') != 'ip' or
                rule.get('table') != 'netbird' or rule.get('chain') != 'netbird-rt-fwd'):
            continue
        if managed(rule, cfg):
            existing.append(rule)
            continue
        expr = rule.get('expr', [])
        if any(_match(x, 'daddr', _prefix(cfg['virtual'])) for x in expr):
            source = native(rule, cfg)
            handle = rule.get('handle')
            if source is None or type(handle) is not int or handle <= 0:
                raise Refused('NetBird route ACL format changed; no unsafe rewrite')
            candidates.append((handle, source))

    # A NetBird policy refresh can install new native grants before deleting
    # the previously rewritten grants. Leaving both generations in place
    # retains revoked access. Delete the *verified* old OpenMain handles and
    # replace the currently native handles in ONE nftables transaction.
    # No unowned/unknown rule may be deleted or rewritten.
    chosen = candidates if candidates else [
        (rule.get('handle'), rule['expr'][2]['match']['right'])
        for rule in existing]
    if not chosen or len(chosen) > MAX_MANAGED_ACLS or len(existing) > MAX_MANAGED_ACLS:
        raise Refused('Unexpected count of NetBird ACLs for BINAT')
    if any(type(handle) is not int or handle <= 0 or not authorized_source(source)
           for handle, source in chosen):
        raise Refused('Unexpected NetBird ACL identity or source')
    sources = [source for _, source in chosen]
    handles = [handle for handle, _ in chosen]
    old_handles = [rule.get('handle') for rule in existing]
    if (any(type(handle) is not int or handle <= 0 for handle in old_handles) or
            len(set(handles + old_handles)) != len(handles + old_handles) or
            len(set(sources)) != len(sources)):
        raise Refused('Duplicate NetBird ACL source or handle')
    if existing and not candidates:
        if not any(SOURCE_RE.fullmatch(source) for source in sources):
            raise Refused('No customer source group in existing managed ACLs')
        return ''
    deletes = ''.join(
        f'delete rule ip netbird netbird-rt-fwd handle {handle}\n'
        for handle in old_handles)
    # If NetBird has removed the customer group while retaining only an
    # explicit peer grant, revoke stale OpenMain authorizations now. The
    # native rule will not match the post-DNAT destination; the follow-up
    # verification fails closed until the customer policy returns.
    if not any(SOURCE_RE.fullmatch(source) for source in sources):
        if deletes:
            return deletes
        raise Refused('No NetBird-managed customer source group present')
    virtual = ipaddress.IPv4Network(cfg['virtual'])
    rewritten = ''.join(
        f'replace rule ip netbird netbird-rt-fwd handle {handle} '
        f'iifname "{cfg["overlay"]}" oifname "{cfg["lan"]}" '
        f'ip saddr {source} ct status dnat '
        f'ct original daddr & {virtual.netmask} == {virtual.network_address} '
        f'ip daddr {cfg["real"]} counter accept comment "{MARKER}"\n'
        for handle, source in candidates)
    return deletes + rewritten


def nft(*args):
    result = subprocess.run(['nft', *args], capture_output=True, timeout=8)
    if result.returncode:
        raise Refused('nftables read/validation/apply failed')
    return result.stdout


def main():
    cfg = configuration()
    rules = json.loads(nft('-j', 'list', 'chain', 'ip', 'netbird', 'netbird-rt-fwd'))
    command = transaction(rules, cfg)
    if not command:
        return
    sources = re.findall(r'ip saddr (@nb-[0-9a-f]{8}) ', command)
    if not sources and 'replace rule ' in command:
        raise Refused('Missing NetBird source-set binding')
    for source in sources:
        nft('-j', 'list', 'set', 'ip', 'netbird', source[1:])
    with tempfile.NamedTemporaryFile(mode='w', prefix='openmain-acl-', delete=False) as file:
        file.write(command)
        path = file.name
    try:
        nft('-c', '-f', path)
        nft('-f', path)
        # Ensure refresh races did not leave a new mixed generation in place.
        observed = json.loads(nft('-j', 'list', 'chain', 'ip', 'netbird', 'netbird-rt-fwd'))
        if transaction(observed, cfg):
            raise Refused('NetBird ACL changed while reconciling')
    finally:
        os.unlink(path)


if __name__ == '__main__':
    try:
        main()
    except (Refused, ValueError, KeyError, TypeError, OSError, subprocess.SubprocessError):
        print('BINAT/NetBird-ACL nicht kompatibel oder nicht bereit; keine Policy-Freigabe hinzugefuegt.', file=sys.stderr)
        sys.exit(1)
